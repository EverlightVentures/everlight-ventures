def sha(content: str) -> str:
    return hashlib.sha256(content.encode("utf-8")).hexdigest()[:12]


def write_if_changed(path: Path, content: str) -> tuple[bool, str]:
    path.parent.mkdir(parents=True, exist_ok=True)
    current = path.read_text(encoding="utf-8") if path.exists() else ""

    # Compare ignoring the auto-generated timestamp line, so we don't
    # rewrite-and-churn every minute when nothing of substance changed.
    def strip_stamp(s: str) -> str:
        return "\n".join(line for line in s.splitlines() if "AUTO-GENERATED by" not in line)

    if strip_stamp(current) == strip_stamp(content):
        return False, sha(content)
    path.write_text(content, encoding="utf-8")
    return True, sha(content)


